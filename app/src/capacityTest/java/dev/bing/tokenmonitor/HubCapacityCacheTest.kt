/** Optional source-oracle integration; all large bodies are generated by the loopback fixture at runtime. */
class HubCapacityCacheTest {
    private data class Shape(val name: String, val devices: Int, val sessionsPerDevice: Int, val modelsPerDevice: Int,
        val days: Int, val monthlyRows: Int, val projected: Boolean, val emptySignature: Boolean) {
        val sessions get() = devices * sessionsPerDevice
        val models get() = devices * modelsPerDevice
    }
    private data class PayloadMeasurement(val bytes: Long, val sha256: String)
    private data class SeedFacts(val observedIds: List<String>, val aliasProjection: Map<String, BigInteger>,
        val signature: String, val retainedStatsBytes: Long)
    private data class Expected(val shape: Shape, val scenario: JsonObject) {
        private val sizes = scenario.getValue("sizes").jsonObject
        private val business = scenario.getValue("businessChecks").jsonObject
        private val digests = scenario.getValue("publicPayloadDigests").jsonObject
        fun bytes(name: String) = sizes.getValue(name).jsonPrimitive.long
        fun business(name: String) = business.getValue(name).jsonPrimitive.content
        fun digest(name: String) = digests.getValue(name).jsonPrimitive.content
        fun verifyShape() {
            val actual = scenario.getValue("shape").jsonObject
            assertEquals(shape.name, actual.getValue("name").jsonPrimitive.content)
            assertEquals(shape.devices, actual.getValue("devices").jsonPrimitive.int)
            assertEquals(shape.sessionsPerDevice, actual.getValue("sessionsPerDevicePerPeriod").jsonPrimitive.int)
            assertEquals(shape.modelsPerDevice, actual.getValue("modelsPerDevice").jsonPrimitive.int)
            assertEquals(shape.days, actual.getValue("days").jsonPrimitive.int)
            assertEquals(shape.sessions, business.getValue("sessionsPerPeriod").jsonPrimitive.int)
            assertEquals(shape.sessions, business.getValue("projectsPerPeriod").jsonPrimitive.int)
            assertEquals(shape.models, business.getValue("modelIdsPerPeriodAndHistoryDay").jsonPrimitive.int)
            assertEquals(shape.days, business.getValue("retainedDailyRows").jsonPrimitive.int)
            assertEquals(shape.monthlyRows, business.getValue("retainedMonthlyRows").jsonPrimitive.int)
            assertTrue(business.getValue("everySessionAndProjectChecked").jsonPrimitive.boolean)
            assertTrue(business.getValue("everyDailyAndMonthlyModelChecked").jsonPrimitive.boolean)
        }
    }

    @Test fun completeEightDeviceStatsAnd370DayHistorySurviveIndependentV2CacheBoundary() = runScenario(
        Shape("combined-cache-8-devices", 8, 180, 20, 370, 13, projected = false, emptySignature = true))

    @Test fun projectedSixteenDeviceTopLevelDetailsAndOrderedMetadataSurviveColdRestore() = runScenario(
        Shape("transport-16-devices", 16, 300, 20, 31, 2, projected = true, emptySignature = false))

    private fun runScenario(shape: Shape) {
        val instrumentation = InstrumentationRegistry.getInstrumentation()
        val context = instrumentation.targetContext
        val port = InstrumentationRegistry.getArguments().getString("capacityPort")?.toIntOrNull() ?: 18748
        require(port in 1..65535)
        val base = "http://127.0.0.1:$port"
        val name = "test-capacity-cache-${UUID.randomUUID()}.bin"
        val store = HubStore(context, name)
        val cacheFile = File(context.noBackupFilesDir, name)
        val reportFile = File(context.getExternalFilesDir(null), "capacity-cache-${shape.name}-public.json")
        reportFile.delete()
        val secret = UUID.randomUUID().toString()
        val measured = linkedMapOf<String, PayloadMeasurement>()
        val client = OkHttpClient.Builder().connectTimeout(10, TimeUnit.SECONDS).readTimeout(90, TimeUnit.SECONDS)
            .callTimeout(120, TimeUnit.SECONDS).addInterceptor { chain ->
                val original = chain.request()
                val path = original.url.encodedPath.removePrefix("/api/")
                if (!original.url.encodedPath.startsWith("/api/")) chain.proceed(original)
                else {
                    // The public source oracle has no authentication; the random cache credential stays local.
                    val response = chain.proceed(original.newBuilder().url("$base/capacity/${shape.name}/$path")
                        .removeHeader("Authorization").build())
                    val body = response.body
                    val hashing = HashingSource.sha256(body.source())
                    var bytes = 0L
                    val source = object : ForwardingSource(hashing) {
                        override fun read(sink: okio.Buffer, byteCount: Long): Long = super.read(sink, byteCount).also {
                            if (it > 0) bytes += it
                        }
                        override fun close() {
                            try { super.close() }
                            finally { measured[path] = PayloadMeasurement(bytes, hashing.hash.hex()) }
                        }
                    }.buffer()
                    response.newBuilder().body(object : ResponseBody() {
                        override fun contentType(): MediaType? = body.contentType()
                        override fun contentLength(): Long = body.contentLength()
                        override fun source(): BufferedSource = source
                    }).build()
                }
            }.build()
        val heap = HeapSampler()
        val started = SystemClock.elapsedRealtimeNanos()
        val timings = JSONObject()
        var phase = "setup"
        var passed = false
        var cipherBytes = 0L
        var retainedStatsBytes = 0L
        var hashUnchanged = false
        var observedIds = 0
        var coldReadFailureKind: String? = null
        heap.start()
        try {
            // This optional acceptance suite targets the verified emulator growth limit, not a largeHeap run.
            assertEquals("Capacity acceptance requires the 192 MiB Java heap", 192L * MIB, Runtime.getRuntime().maxMemory())
            val expected = readExpected(client, base, shape).also(Expected::verifyShape)
            phase = "source-read-native-parse-save"
            val seedStarted = SystemClock.elapsedRealtimeNanos()
            // The original Snapshot and source strings leave this method before cold loading begins.
            val facts = seedAndSave(HubHttp(client), base, secret, store, expected)
            timings.put("sourceReadNativeParseSaveMs", elapsedMs(seedStarted))
            retainedStatsBytes = facts.retainedStatsBytes
            observedIds = facts.observedIds.size
            assertPayload(measured.getValue("stats"), expected.bytes("statsUtf8Bytes"), expected.digest("statsSha256"))
            assertPayload(measured.getValue("history"), expected.bytes("historyUtf8Bytes"), expected.digest("historySha256"))
            if (shape.projected) {
                assertEquals(21_667_533L, measured.getValue("stats").bytes)
                assertTrue(measured.getValue("stats").bytes > 8L * MIB)
                assertTrue(retainedStatsBytes >= expected.bytes("topLevelPeriodsUtf8Bytes"))
                assertTrue("Top-level details remain larger than the former retained ceiling", retainedStatsBytes > 8L * MIB)
            } else {
                assertEquals(6_579_790L, measured.getValue("stats").bytes)
                assertEquals(5_553_856L, measured.getValue("history").bytes)
                assertEquals(measured.getValue("stats").bytes, retainedStatsBytes)
                assertTrue(measured.getValue("stats").bytes < 8L * MIB)
                assertTrue("The raw combined cache must exceed the old independent 10 MiB limit",
                    measured.getValue("stats").bytes + measured.getValue("history").bytes > 10L * MIB)
            }
            cipherBytes = cacheFile.length()
            assertTrue(cipherBytes in 30L..10L * MIB)
            cacheFile.inputStream().use { assertEquals(2, it.read()) }
            val beforeReadHash = hash(cacheFile)
            phase = "cold-store-read"
            var restored: SavedHub? = null
            var readerCalls = 0
            var writerCalls = 0
            val reader = object : HubStore(context, name) {
                override fun load(): SavedHub? {
                    readerCalls++
                    return super.load().also { restored = it }
                }
                override fun save(record: SavedHub) {
                    writerCalls++
                    error("Cold cache read attempted a write")
                }
            }
            val coldStarted = SystemClock.elapsedRealtimeNanos()
            val record = try {
                reader.load() ?: error("Cold store did not recover its authenticated record")
            } catch (error: Throwable) {
                coldReadFailureKind = error.javaClass.simpleName
                // No original message, cause or suppressed error can reveal cached string contents.
                throw AssertionError("Cold cache read failed: ${error.javaClass.simpleName}").apply {
                    stackTrace = error.stackTrace
                }
            }
            timings.put("coldStoreReadMs", elapsedMs(coldStarted))
            assertTrue(restored === record)
            assertEquals(1, readerCalls)
            assertEquals(0, writerCalls)
            assertTrue(record.credential == secret)
            assertEquals(CACHED_ADDRESS, record.address)
            assertEquals(SAVED_AT, record.savedAt)
            assertEquals(facts.signature, record.historySignature)
            assertEquals(facts.observedIds, record.observedModelIds)
            // Store already parsed this exact Snapshot. Never build a second full tree or model here.
            val snapshot = record.parsedSnapshot ?: error("Cold store did not provide its parsed Snapshot")
            phase = "complete-cold-business-checks"
            val checksStarted = SystemClock.elapsedRealtimeNanos()
            assertSnapshot(snapshot, expected)
            assertEquals(facts.observedIds, snapshot.observedModelIds)
            val names = ModelNamesParser.parse(record.modelNames ?: error("Alias settings were lost"))
            assertEquals(facts.aliasProjection, names.project(snapshot.periods.getValue("today").models, snapshot.observedModelIds))
            assertHistory(HistoryParser.parse(record.history ?: error("History was lost")), expected)
            hashUnchanged = beforeReadHash == hash(cacheFile)
            assertTrue("Cold restore must leave ciphertext unchanged", hashUnchanged)
            timings.put("completeColdBusinessChecksMs", elapsedMs(checksStarted))
            passed = true
            phase = "complete"
        } finally {
            heap.close()
            try {
                val memory = Debug.MemoryInfo().also(Debug::getMemoryInfo)
                val payloads = JSONObject()
                measured.forEach { (path, measurement) -> payloads.put(path, JSONObject()
                    .put("decodedUtf8Bytes", measurement.bytes).put("sha256", measurement.sha256)) }
                val report = JSONObject().put("schemaVersion", 1).put("shape", shape.name).put("passed", passed)
                    .put("lastPhase", phase).put("fixtureReduced", false).put("physicalDeviceMeasured", false)
                    .put("coldReadFailureKind", coldReadFailureKind ?: JSONObject.NULL)
                    .put("fixture", JSONObject().put("devices", shape.devices).put("sessionsPerPeriod", shape.sessions)
                        .put("projectsPerPeriod", shape.sessions).put("modelsPerPeriod", shape.models)
                        .put("dailyRows", shape.days).put("monthlyRows", shape.monthlyRows))
                    .put("completeBusinessChecksPassed", passed)
                    .put("javaHeapMaxBytes", Runtime.getRuntime().maxMemory()).put("javaUsedBeforeBytes", heap.javaBefore)
                    .put("sampledJavaUsedPeakBytes", heap.javaPeak.get()).put("nativeAllocatedBeforeBytes", heap.nativeBefore)
                    .put("sampledNativeAllocatedPeakBytes", heap.nativePeak.get()).put("sampleIntervalMs", 10)
                    .put("finalTotalPssKiB", memory.totalPss).put("elapsedMs", elapsedMs(started)).put("timings", timings)
                    .put("v2CipherBytes", cipherBytes).put("retainedStatsUtf8Bytes", retainedStatsBytes)
                    .put("sourcePayloads", payloads).put("observedModelIds", observedIds)
                    .put("historySignatureKind", if (shape.emptySignature) "explicit-empty" else "snapshot-revision")
                    .put("ciphertextUnchangedByColdRead", hashUnchanged)
                    .put("measurementScope", "Runtime used heap samples and Android Debug memory; no frame or physical-phone measurement")
                reportFile.writeText(report.toString(2))
            } finally {
                store.clear()
                client.connectionPool.evictAll()
                client.dispatcher.executorService.shutdown()
            }
        }
    }

    /** Return compact expected facts only, so original and restored Snapshots are never retained together. */
    private fun seedAndSave(http: HubHttp, base: String, secret: String, store: HubStore, expected: Expected): SeedFacts {
        val shape = expected.shape
        val projected = if (shape.projected) http.readStats(base, secret) else null
        val body = projected?.body ?: http.read(base, "stats", secret)
        val native = if (projected != null) HubParser.parse(projected) else HubParser.parse(body)
        assertSnapshot(native, expected)
        val ids = native.observedModelIds.toList()
        val aliasBody = aliasBody(shape)
        val names = ModelNamesParser.parse(aliasBody)
        val aliases = names.project(native.periods.getValue("today").models, ids)
        val signature = if (shape.emptySignature) "" else native.historyRevision ?: error("Original Hub revision missing")
        val history = http.readLarge(base, "history", secret)
        val retainedBytes = utf8Bytes(body)
        // Loopback HTTP is a transport-only injection; persist a normal valid HTTPS connection.
        store.save(SavedHub(CACHED_ADDRESS, secret, body, SAVED_AT, history = history, modelNames = aliasBody,
            historySignature = signature, observedModelIds = ids))
        return SeedFacts(ids, aliases, signature, retainedBytes)
    }

    private fun readExpected(client: OkHttpClient, base: String, shape: Shape): Expected = client.newCall(
        Request.Builder().url("$base/capacity/${shape.name}/expected").get().build()).execute().use { response ->
        assertTrue(response.isSuccessful)
        val result = StringBuilder()
        response.body.charStream().use { reader ->
            val buffer = CharArray(2048)
            while (true) {
                val size = reader.read(buffer)
                if (size < 0) break
                require(result.length + size <= 64 * 1024) { "Unexpected source report size" }
                result.append(buffer, 0, size)
            }
        }
        Expected(shape, Json.parseToJsonElement(result.toString()).jsonObject)
    }

    private fun assertSnapshot(snapshot: Snapshot, expected: Expected) {
        val shape = expected.shape
        assertEquals(shape.devices, snapshot.devices.size)
        assertFalse(snapshot.detailIncomplete)
        val allModels = modelIds(shape)
        assertEquals(allModels.size, snapshot.observedModelIds.size)
        assertEquals(allModels.toSet(), snapshot.observedModelIds.toSet())
        for ((name, multiplier) in listOf("today" to 1L, "month" to 9L, "allTime" to shape.days.toLong())) {
            val period = snapshot.periods.getValue(name)
            val tokens = shape.sessions.toLong() * SESSION_TOKENS * multiplier
            assertEquals(tokens, period.tokens)
            money(SESSION_COST.multiply(BigDecimal.valueOf(shape.sessions.toLong() * multiplier)), period.cost)
            assertEquals(shape.sessions.toLong() * 17 * multiplier, period.unpriced)
            assertEquals(shape.sessions.toLong() * 16 * multiplier, period.components.cacheRead)
            assertEquals(shape.sessions.toLong() * 8 * multiplier, period.components.cacheWrite)
            assertEquals(shape.sessions.toLong() * 7 * multiplier, period.components.output)
            assertEquals(0L, period.components.unclassified)
            assertEquals(tokens, period.tools.getValue("codex"))
            assertEquals(0L, period.sessionsOmitted)
            assertFalse(period.projectsIncomplete)
            assertTrue(period.projectsProvided)
            assertEquals(shape.models, period.models.size)
            val modelTokens = (shape.sessionsPerDevice / shape.modelsPerDevice).toLong() * SESSION_TOKENS * multiplier
            val modelCost = SESSION_COST.multiply(BigDecimal.valueOf((shape.sessionsPerDevice / shape.modelsPerDevice).toLong() * multiplier))
            allModels.forEach { model ->
                assertEquals(modelTokens, period.models.getValue(model))
                assertEquals(modelTokens, period.modelDetails.getValue(model).tokens)
                money(modelCost, period.modelDetails.getValue(model).cost)
            }
            assertEquals(shape.sessions, period.sessions.size)
            assertEquals(shape.sessions, period.projects.size)
            val sessionIds = HashSet<String>()
            period.sessions.forEach { row ->
                val metadata = row.session ?: error("Original session metadata missing")
                val id = metadata.sessionId ?: error("Original session ID missing")
                val coordinates = coordinates(id, shape)
                assertTrue(sessionIds.add(id))
                assertEquals(SESSION_TOKENS * multiplier, row.tokens)
                money(SESSION_COST.multiply(BigDecimal.valueOf(multiplier)), row.cost)
                assertEquals(17L * multiplier, row.unpriced)
                assertEquals("codex", row.tool)
                assertEquals("Public project $id", metadata.projectLabel)
                assertEquals(mapOf(modelId(coordinates.first, coordinates.second % shape.modelsPerDevice) to SESSION_TOKENS * multiplier), metadata.models)
            }
            val projects = HashSet<String>()
            period.projects.forEach { row ->
                val project = row.project ?: error("Original project metadata missing")
                val label = project.label ?: error("Original project label missing")
                assertTrue(label.startsWith("Public project "))
                val id = label.removePrefix("Public project ")
                coordinates(id, shape)
                assertTrue(projects.add(id))
                assertEquals(label.lowercase(), row.id)
                assertEquals(SESSION_TOKENS * multiplier, row.tokens)
                assertEquals(row.tokens, project.tokens)
                assertEquals(row.tokens, project.clients.getValue("codex"))
                money(SESSION_COST.multiply(BigDecimal.valueOf(multiplier)), row.cost)
                assertEquals(17L * multiplier, row.unpriced)
            }
            assertEquals(sessionIds, projects)
        }
        assertEquals(expected.business("exactTodayTokens").toLong(), snapshot.periods.getValue("today").tokens)
        assertEquals(expected.business("exactAllTimeTokens").toLong(), snapshot.periods.getValue("allTime").tokens)
        money(expected.business("exactTodayCost"), snapshot.periods.getValue("today").cost)
        money(expected.business("exactAllTimeCost"), snapshot.periods.getValue("allTime").cost)
        snapshot.devices.forEachIndexed { index, device ->
            assertEquals("public-device-${index.toString().padStart(2, '0')}", device.id)
            assertEquals(setOf("today", "month", "allTime"), device.periods.keys)
            for ((name, multiplier) in listOf("today" to 1L, "month" to 9L, "allTime" to shape.days.toLong())) {
                val period = device.periods.getValue(name)
                val tokens = shape.sessionsPerDevice.toLong() * SESSION_TOKENS * multiplier
                assertEquals(tokens, period.tokens)
                money(SESSION_COST.multiply(BigDecimal.valueOf(shape.sessionsPerDevice.toLong() * multiplier)), period.cost)
                assertEquals(shape.sessionsPerDevice.toLong() * 17 * multiplier, period.unpriced)
                assertEquals(mapOf("codex" to tokens), period.tools)
                assertEquals(setOf("codex"), period.clientModels.keys)
                val clientModels = period.clientModels.getValue("codex")
                assertEquals(shape.modelsPerDevice, clientModels.size)
                val modelTokens = (shape.sessionsPerDevice / shape.modelsPerDevice).toLong() * SESSION_TOKENS * multiplier
                (0 until shape.modelsPerDevice).forEach { model ->
                    assertEquals(modelTokens, clientModels.getValue(modelId(index, model)))
                }
            }
            // The longstanding native Device model exposes only a summary of today.
            // Duplicate sessions/projects are excluded even when the saved body is unprojected.
            assertEquals(setOf("today"), device.periodDetails.keys)
            val today = device.periodDetails.getValue("today")
            val sessions = shape.sessionsPerDevice.toLong()
            assertEquals(sessions * SESSION_TOKENS, today.tokens)
            money(SESSION_COST.multiply(BigDecimal.valueOf(sessions)), today.cost)
            assertEquals(sessions * 17, today.unpriced)
            assertEquals(sessions * 16, today.components.cacheRead)
            assertEquals(sessions * 8, today.components.cacheWrite)
            assertEquals(sessions * 7, today.components.output)
            assertEquals(0L, today.components.unclassified)
            assertEquals(0, today.sessions.size)
            assertEquals(0, today.projects.size)
        }
    }

    private fun assertHistory(history: HubHistory, expected: Expected) {
        val shape = expected.shape
        assertEquals(shape.days, history.daily.size)
        assertEquals(shape.monthlyRows, history.monthly.size)
        assertEquals(expected.business("lastDay"), history.daily.first().date)
        assertEquals(expected.business("firstDay"), history.daily.last().date)
        val allModels = modelIds(shape)
        val first = LocalDate.parse(expected.business("firstDay"))
        val dates = (0 until shape.days).map { first.plusDays(it.toLong()).toString() }.toSet()
        assertEquals(dates, history.daily.map { it.date }.toSet())
        val months = dates.groupingBy { it.take(7) }.eachCount()
        assertEquals(months.keys, history.monthly.map { it.date }.toSet())
        val dayTokens = shape.sessions.toLong() * SESSION_TOKENS
        val dayCost = SESSION_COST.multiply(BigDecimal.valueOf(shape.sessions.toLong()))
        val modelTokens = (shape.sessionsPerDevice / shape.modelsPerDevice).toLong() * SESSION_TOKENS
        val modelCost = SESSION_COST.multiply(BigDecimal.valueOf((shape.sessionsPerDevice / shape.modelsPerDevice).toLong()))
        fun row(row: HistoryRow, days: Int) {
            assertEquals(dayTokens * days, row.tokens)
            money(dayCost.multiply(BigDecimal.valueOf(days.toLong())), row.cost)
            assertEquals(shape.sessions.toLong() * 17 * days, row.unpricedTokens)
            assertEquals(dayTokens * days, row.perClient.getValue("codex").tokens)
            money(dayCost.multiply(BigDecimal.valueOf(days.toLong())), row.perClient.getValue("codex").cost)
            assertEquals(shape.models, row.perModel.size)
            allModels.forEach { id ->
                assertEquals(modelTokens * days, row.perModel.getValue(id).tokens)
                money(modelCost.multiply(BigDecimal.valueOf(days.toLong())), row.perModel.getValue(id).cost)
            }
        }
        history.daily.forEach { row(it, 1) }
        history.monthly.forEach { row(it, months.getValue(it.date)) }
        val summary = history.summary ?: error("Original history summary missing")
        assertEquals(expected.business("exactAllTimeTokens").toLong(), summary.totalTokens)
        money(expected.business("exactAllTimeCost"), summary.totalCost)
        assertEquals(shape.sessions.toLong() * 17 * shape.days, summary.unpricedTokens)
        assertEquals(shape.days.toLong(), summary.activeDays)
        assertEquals(shape.sessions.toLong() * shape.days, summary.messages)
    }

    private fun coordinates(id: String, shape: Shape): Pair<Int, Int> {
        val match = SESSION_ID.matchEntire(id) ?: error("Unexpected public fixture session ID")
        val device = match.groupValues[1].toInt()
        val session = match.groupValues[2].toInt()
        assertTrue(device in 0 until shape.devices && session in 0 until shape.sessionsPerDevice)
        return device to session
    }
    private fun modelId(device: Int, model: Int) = "public-d${device.toString().padStart(2, '0')}-m${model.toString().padStart(2, '0')}"
    private fun modelIds(shape: Shape) = (0 until shape.devices).flatMap { device -> (0 until shape.modelsPerDevice).map { modelId(device, it) } }
    private fun aliasBody(shape: Shape) = """{"ok":true,"value":{"modelAliases":{"${modelId(0, 0)}":"public-shared-alias","${modelId(shape.devices - 1, 0)}":"public-shared-alias"},"modelAliasGrouping":"prefix"}}"""
    private fun money(expected: String, actual: String?) = money(BigDecimal(expected), actual)
    private fun money(expected: BigDecimal, actual: String?) {
        assertNotNull(actual)
        assertTrue("Exact decimal cost must survive transport and cache", expected.compareTo(BigDecimal(actual!!)) == 0)
    }
    private fun assertPayload(actual: PayloadMeasurement, bytes: Long, sha256: String) {
        assertEquals(bytes, actual.bytes)
        assertEquals(sha256, actual.sha256)
    }
    private fun utf8Bytes(value: String): Long {
        var bytes = 0L
        OutputStreamWriter(object : OutputStream() {
            override fun write(value: Int) { bytes++ }
            override fun write(value: ByteArray, offset: Int, length: Int) { bytes += length }
        }, Charsets.UTF_8).use { it.write(value) }
        return bytes
    }
    private fun hash(file: File): String {
        val digest = MessageDigest.getInstance("SHA-256")
        file.inputStream().use { input ->
            val bytes = ByteArray(8192)
            while (true) { val size = input.read(bytes); if (size < 0) break; digest.update(bytes, 0, size) }
        }
        return digest.digest().joinToString("") { "%02x".format(it.toInt() and 255) }
    }
    private fun elapsedMs(started: Long) = (SystemClock.elapsedRealtimeNanos() - started) / 1_000_000.0
    private class HeapSampler : AutoCloseable {
        private val running = AtomicBoolean()
        val javaBefore = javaUsed()
        val nativeBefore = Debug.getNativeHeapAllocatedSize()
        val javaPeak = AtomicLong(javaBefore)
        val nativePeak = AtomicLong(nativeBefore)
        private val thread = Thread({
            while (running.get()) {
                javaPeak.accumulateAndGet(javaUsed(), ::maxOf)
                nativePeak.accumulateAndGet(Debug.getNativeHeapAllocatedSize(), ::maxOf)
                try { Thread.sleep(10) } catch (_: InterruptedException) { break }
            }
        }, "public-capacity-cache-heap-sampler").apply { isDaemon = true }
        fun start() { running.set(true); thread.start() }
        override fun close() {
            javaPeak.accumulateAndGet(javaUsed(), ::maxOf)
            nativePeak.accumulateAndGet(Debug.getNativeHeapAllocatedSize(), ::maxOf)
            running.set(false); thread.interrupt(); thread.join(1000)
        }
        private fun javaUsed() = Runtime.getRuntime().let { it.totalMemory() - it.freeMemory() }
    }
    companion object {
        private const val MIB = 1024 * 1024
        private const val CACHED_ADDRESS = "https://public-capacity.invalid"
        private const val SESSION_TOKENS = 5_000_000_123L
        private val SESSION_COST = BigDecimal("0.015625")
        private val SESSION_ID = Regex("public-d(\\d{2})-s(\\d{3})")
        private val SAVED_AT = Instant.parse("2026-10-09T08:00:00.000Z").toEpochMilli()
    }
}
